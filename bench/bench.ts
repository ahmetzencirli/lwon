// Token and byte comparison of JSON, TOON and LWON on synthetic but realistic datasets.
// Run with `npm run bench`; writes bench/RESULTS.md.
import { writeFileSync } from 'node:fs';
import { encode as countTokens } from 'gpt-tokenizer';
import { encode as toToon } from '@toon-format/toon';
import { decode, encode } from '../packages/lwon/src/index.ts';
import { canonical } from '../packages/lwon/test/util.ts';

/** Seeded PRNG so every run produces the same datasets. */
function rng(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const r = rng(42);
const pick = <T>(xs: T[]): T => xs[Math.floor(r() * xs.length)];
const int = (n: number) => Math.floor(r() * n);
const FIRST = ['Ayşe', 'Mehmet', 'Alice', 'Bob', 'Carlos', 'Mei', 'Fatima', 'John', 'Elif', 'Kenji'];
const LAST = ['Yılmaz', 'Kaya', 'Smith', 'García', 'Chen', 'Khan', 'Müller', 'Demir'];
const CITIES = ['Istanbul', 'Ankara', 'Berlin', 'New York', 'Tokyo', 'São Paulo', 'London'];
const WORDS = ['fix', 'crash', 'when', 'loading', 'user', 'profile', 'cache', 'timeout', 'add', 'support', 'for', 'dark', 'mode', 'api'];
const sentence = (n: number) => Array.from({ length: n }, () => pick(WORDS)).join(' ');
const date = () => new Date(Date.UTC(2026, int(12), 1 + int(28), int(24), int(60))).toISOString();

const users = Array.from({ length: 100 }, (_, i) => ({
  id: i + 1,
  name: `${pick(FIRST)} ${pick(LAST)}`,
  email: `user${i + 1}@example.com`,
  role: pick(['admin', 'editor', 'viewer']),
  active: r() < 0.8,
  score: int(1000),
}));

const orders = Array.from({ length: 50 }, (_, i) => ({
  orderId: `ORD-${10000 + i}`,
  createdAt: date(),
  status: pick(['paid', 'shipped', 'delivered', 'refunded']),
  customer: { id: 500 + int(200), name: `${pick(FIRST)} ${pick(LAST)}`, address: { city: pick(CITIES), zip: String(10000 + int(89999)) } },
  items: Array.from({ length: 1 + int(4) }, () => ({ sku: `SKU-${int(9999)}`, qty: 1 + int(3), price: Math.round(r() * 20000) / 100 })),
  tags: Array.from({ length: int(3) }, () => pick(['gift', 'express', 'b2b', 'promo'])),
}));

const issues = Array.from({ length: 30 }, (_, i) => ({
  number: 4000 + i,
  title: sentence(4 + int(5)),
  state: pick(['open', 'closed']),
  user: { login: `dev${int(50)}`, id: 9000 + int(1000), site_admin: false },
  labels: Array.from({ length: int(3) }, () => {
    const name = pick(['bug', 'enhancement', 'docs', 'good first issue']);
    return { name, color: pick(['d73a4a', 'a2eeef', '0075ca', '7057ff']) };
  }),
  assignee: r() < 0.5 ? null : { login: `dev${int(50)}`, id: 9000 + int(1000), site_admin: false },
  comments: int(20),
  created_at: date(),
  body: r() < 0.3 ? null : sentence(10 + int(15)),
}));

let node = 0;
const menu = (depth: number): object[] =>
  Array.from({ length: depth === 0 ? 0 : 2 + int(2) }, () => {
    const id = ++node;
    return { id, title: `Section ${id}`, path: `/s/${id}`, children: menu(depth - 1) };
  });

const logs = Array.from({ length: 80 }, () => {
  const e: Record<string, unknown> = { ts: date(), level: pick(['info', 'info', 'warn', 'error']), msg: sentence(5) };
  if (r() < 0.5) e.requestId = `req-${int(1e6)}`;
  if (r() < 0.3) e.userId = int(5000);
  if (e.level === 'error') e.error = { code: pick(['E_TIMEOUT', 'E_DB', 'E_AUTH']), stack: sentence(6) };
  if (r() < 0.2) e.durationMs = int(3000);
  return e;
});

const search = {
  query: 'lwon token savings',
  total: 25,
  results: Array.from({ length: 25 }, (_, i) => ({
    rank: i + 1,
    title: sentence(6),
    url: `https://example.com/${pick(WORDS)}/${int(1e5)}`,
    snippet: sentence(20),
    score: Math.round(r() * 1000) / 1000,
    meta: { lang: pick(['en', 'tr', 'de']), published: date() },
  })),
};

const datasets: [string, string, unknown][] = [
  ['users', 'Flat table, 100 rows', users],
  ['orders', 'Nested objects and arrays, 50 orders', orders],
  ['issues', 'GitHub-style issues with nullable objects, 30 rows', issues],
  ['menu', 'Recursive tree, 3 levels', menu(3)],
  ['logs', 'Log events with optional fields, 80 rows', logs],
  ['search', 'Search tool result: object with a result list', search],
];

const pct = (a: number, b: number) => `${((a / b - 1) * 100).toFixed(0)}%`;
const lines = [
  '# Token benchmark',
  '',
  'Tokens counted with the o200k tokenizer (`gpt-tokenizer`), a proxy until Claude token counts are added.',
  'Percentages are against **minified JSON**, the honest baseline. Generated by `npm run bench`.',
  '',
  '| Dataset | Shape | JSON indented | JSON minified | TOON | LWON | LWON vs JSON | LWON vs TOON |',
  '|---|---|--:|--:|--:|--:|--:|--:|',
];
for (const [name, shape, data] of datasets) {
  const lwon = encode(data);
  if (JSON.stringify(canonical(decode(lwon))) !== JSON.stringify(canonical(data))) throw new Error(`${name}: LWON did not round-trip`);
  const t = {
    pretty: countTokens(JSON.stringify(data, null, 2)).length,
    min: countTokens(JSON.stringify(data)).length,
    toon: countTokens(toToon(data)).length,
    lwon: countTokens(lwon).length,
  };
  lines.push(`| ${name} | ${shape} | ${t.pretty} | ${t.min} | ${t.toon} | ${t.lwon} | ${pct(t.lwon, t.min)} | ${pct(t.lwon, t.toon)} |`);
  console.log(name.padEnd(8), t);
}
writeFileSync(new URL('RESULTS.md', import.meta.url), lines.join('\n') + '\n');
